"""HTM engine generated from integer sticker geometry in Kociemba URFDLB.

Axes: +x right, +y up, +z front. Clockwise is -90 degrees about the
outward normal, viewed from outside. No solver, HTTP, config, or secrets.
"""
from collections import Counter
from collections.abc import Iterable
from dataclasses import dataclass
from types import MappingProxyType

Vector = tuple[int, int, int]
FACELET_ORDER = 'URFDLB'
SOLVED = ''.join(face * 9 for face in FACELET_ORDER)
MOVES = tuple(face + suffix for face in 'UDLRFB' for suffix in ('', "'", '2'))

# Outward normal, screen-right, screen-down for each face in the README net.
# These define sticker geometry, not hand-transcribed move permutations.
_BASES = {
    'U': ((0, 1, 0), (1, 0, 0), (0, 0, 1)),
    'R': ((1, 0, 0), (0, 0, -1), (0, -1, 0)),
    'F': ((0, 0, 1), (1, 0, 0), (0, -1, 0)),
    'D': ((0, -1, 0), (1, 0, 0), (0, 0, -1)),
    'L': ((-1, 0, 0), (0, 0, 1), (0, -1, 0)),
    'B': ((0, 0, -1), (-1, 0, 0), (0, -1, 0)),
}


@dataclass(frozen=True)
class Sticker:
    position: Vector
    normal: Vector


def _dot(a: Vector, b: Vector) -> int:
    return sum(x * y for x, y in zip(a, b))


def _clockwise(vector: Vector, axis: Vector) -> Vector:
    """Integer Rodrigues rotation: v' = axis*(axis dot v) - axis cross v."""
    x, y, z = axis
    a, b, c = vector
    cross = (y * c - z * b, z * a - x * c, x * b - y * a)
    along = _dot(axis, vector)
    return tuple(axis[i] * along - cross[i] for i in range(3))


def _make_stickers() -> tuple[Sticker, ...]:
    stickers = []
    for face in FACELET_ORDER:
        normal, right, down = _BASES[face]
        for row in range(3):
            for col in range(3):
                position = tuple(normal[i] + (col - 1) * right[i]
                                 + (row - 1) * down[i] for i in range(3))
                stickers.append(Sticker(position, normal))
    return tuple(stickers)


STICKERS = _make_stickers()


def _make_permutations() -> dict[str, tuple[int, ...]]:
    indices = {sticker: index for index, sticker in enumerate(STICKERS)}
    if len(indices) != 54:
        raise RuntimeError('Sticker geometry is not a 54-position bijection')
    permutations = {}
    for move in MOVES:
        axis = _BASES[move[0]][0]
        turns = 1 if len(move) == 1 else 3 if move[1] == "'" else 2
        gather = [-1] * 54
        for source, sticker in enumerate(STICKERS):
            position, normal = sticker.position, sticker.normal
            if _dot(position, axis) == 1:
                for _ in range(turns):
                    position = _clockwise(position, axis)
                    normal = _clockwise(normal, axis)
            destination = indices[Sticker(position, normal)]
            gather[destination] = source
        if sorted(gather) != list(range(54)):
            raise RuntimeError(f'Non-bijective geometry for {move}')
        permutations[move] = tuple(gather)
    return permutations


# Gather convention: new[destination] = old[permutation[destination]].
MOVE_PERMUTATIONS = MappingProxyType(_make_permutations())


def validate_facelets(facelets: str) -> None:
    """Check format/counts/centres, not arbitrary-state physical solvability.

    Legal scrambles are generated by moves from SOLVED. This check does not
    establish corner/edge orientation or permutation parity of external input.
    """
    if not isinstance(facelets, str) or len(facelets) != 54:
        raise ValueError('facelets must be a 54-character string')
    if Counter(facelets) != Counter(SOLVED):
        raise ValueError('facelets must contain exactly nine of each URFDLB letter')
    if any(facelets[9 * i + 4] != face for i, face in enumerate(FACELET_ORDER)):
        raise ValueError('facelet centres must remain fixed in URFDLB order')


def _permutation(move: str) -> tuple[int, ...]:
    if not isinstance(move, str) or move not in MOVE_PERMUTATIONS:
        raise ValueError('move must exactly match one of the 18 HTM strings')
    return MOVE_PERMUTATIONS[move]


def apply(facelets: str, move: str) -> str:
    """Apply one exact move string, without trimming or autocorrection."""
    validate_facelets(facelets)
    return ''.join(map(facelets.__getitem__, _permutation(move)))


def apply_moves(facelets: str, moves: Iterable[str]) -> str:
    """Apply tokenized moves in order; empty input preserves state."""
    validate_facelets(facelets)
    if isinstance(moves, str):
        raise ValueError('moves must be an iterable of tokens, not an algorithm string')
    for move in moves:
        facelets = ''.join(map(facelets.__getitem__, _permutation(move)))
    return facelets


def inverse_move(move: str) -> str:
    _permutation(move)
    return move + "'" if len(move) == 1 else move[0] if move[1] == "'" else move


def is_solved(facelets: str) -> bool:
    """Fixed orientation has exactly one solved string."""
    return facelets == SOLVED


def to_net(facelets: str) -> str:
    """Render the unchanged 54 stickers as a labelled U / L F R B / D net.

    Rows retain the Kociemba orientation, including back/down faces. Labels,
    spaces and newlines are presentation only; no stickers are added or lost.
    """
    validate_facelets(facelets)
    rows = {
        face: [facelets[i * 9 + row:i * 9 + row + 3] for row in (0, 3, 6)]
        for i, face in enumerate(FACELET_ORDER)
    }
    return '\n'.join(
        ['    U'] + ['    ' + row for row in rows['U']]
        + ['L   F   R   B']
        + [' '.join(rows[face][row] for face in 'LFRB') for row in range(3)]
        + ['    D'] + ['    ' + row for row in rows['D']]
    )
